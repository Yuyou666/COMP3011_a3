package comp3011.assignment1.service;

import java.util.concurrent.atomic.AtomicLong;

import org.springframework.stereotype.Service;

/**
 * Stores cumulative Speech-to-Text token usage for the current
 * application process.
 *
 * AtomicLong is used so multiple transcription requests can update
 * the counters safely without losing values due to race conditions.
 */
@Service
public class GlobalStatsService {

    // Thread-safe counter for total input tokens used by transcription requests.
    private final AtomicLong inputTokens = new AtomicLong(0);

    // Thread-safe counter for total output tokens returned by transcription requests.
    private final AtomicLong outputTokens = new AtomicLong(0);

    /**
     * Returns the current total number of input tokens.
     *
     * @return cumulative input token count
     */
    public long getInputTokens() {
        return inputTokens.get();
    }

    /**
     * Returns the current total number of output tokens.
     *
     * @return cumulative output token count
     */
    public long getOutputTokens() {
        return outputTokens.get();
    }

    /**
     * Adds token usage from one completed transcription request.
     *
     * Atomic operations ensure updates remain correct even when
     * multiple requests finish at the same time.
     *
     * @param input input tokens used by the request
     * @param output output tokens generated by the request
     */
    public void addUsage(long input, long output) {
        inputTokens.addAndGet(input);
        outputTokens.addAndGet(output);
    }
}